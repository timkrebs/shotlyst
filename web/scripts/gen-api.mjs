// scripts/gen-api.mjs — generates one typed client per service from
// api/<service>.yaml into src/api/<service>/ (schema.d.ts + index.ts).
//
// Specs with no paths yet (services not implemented) are skipped. The base
// URL comes from the spec's first `servers` entry, so the ingress prefix is
// written down exactly once, in the contract. Run via `make gen`.
import { readdir, readFile, mkdir, writeFile } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const apiDir = join(root, "api");
const outDir = join(root, "web", "src", "api");

const files = (await readdir(apiDir)).filter((f) => f.endsWith(".yaml") && !f.startsWith("_")).sort();
for (const file of files) {
  const service = file.replace(/\.yaml$/, "");
  const text = await readFile(join(apiDir, file), "utf8");
  if (/^paths:\s*\{\s*\}\s*$/m.test(text)) {
    console.log(`gen:api: skip ${service} (no paths yet)`);
    continue;
  }
  const baseUrl = text.match(/^servers:\s*\n\s*-\s*url:\s*(\S+)/m)?.[1];
  if (!baseUrl) throw new Error(`${file}: missing servers[0].url`);

  const ast = await openapiTS(pathToFileURL(join(apiDir, file)));
  const header = `// GENERATED by web/scripts/gen-api.mjs from api/${file}. Do not edit.\n`;
  await mkdir(join(outDir, service), { recursive: true });
  await writeFile(join(outDir, service, "schema.d.ts"), header + astToString(ast));
  await writeFile(
    join(outDir, service, "index.ts"),
    `/**
 * api/${service}/index.ts — typed client for the ${service} service.
 * GENERATED by web/scripts/gen-api.mjs from api/${file}. Do not edit.
 */
import { createApiClient } from "../client";
import type { components, paths } from "./schema";

export const ${service}Api = createApiClient<paths>("${baseUrl}");
export type Schemas = components["schemas"];
`,
  );
  console.log(`gen:api: ${service} → src/api/${service} (${baseUrl})`);
}
